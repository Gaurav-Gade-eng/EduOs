#!/usr/bin/env python3
"""Generate build-time constants from config/layout.conf.

Usage:
  gen_layout.py layout   <layout.conf> <outdir>      -> boot_constants.inc, layout.h, layout.mk
  gen_layout.py metadata <layout.conf> <kernel.bin> <outdir>
                                                      -> loader_metadata.inc (kernel size)
The build FAILS if the layout is inconsistent or the kernel is too large.
"""
import os
import sys

SECTOR = 512
BOOT_INFO_HEADER = 28   # bytes before the memory range array (see boot_info.h)
RANGE_SIZE = 20


def load(path):
    cfg = {}
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            if "=" not in line:
                sys.exit(f"{path}:{n}: expected KEY=VALUE")
            k, v = (s.strip() for s in line.split("=", 1))
            cfg[k] = int(v, 0)
    return cfg


def validate(c):
    errs = []
    s2_end_addr = c["STAGE2_ADDR"] + c["STAGE2_SECTORS"] * SECTOR
    if s2_end_addr > c["KERNEL_LOAD_ADDR"]:
        errs.append("Stage 2 memory overlaps kernel load address")
    if c["KERNEL_LBA"] < c["STAGE2_LBA"] + c["STAGE2_SECTORS"]:
        errs.append("KERNEL_LBA overlaps Stage 2 sectors")
    if c["KERNEL_LBA"] + c["KERNEL_MAX_SECTORS"] > c["EDUFS_START_LBA"]:
        errs.append("kernel region overlaps EduFS start sector")
    if c["KERNEL_LOAD_ADDR"] + c["KERNEL_MAX_SECTORS"] * SECTOR > c["KERNEL_MAX_END"]:
        errs.append("kernel load region exceeds KERNEL_MAX_END")
    if c["KERNEL_MAX_END"] > c["PM_STACK_TOP"]:
        errs.append("kernel region overlaps the loader's protected-mode stack")
    if c["BOOT_INFO_ADDR"] + BOOT_INFO_HEADER + c["BOOT_MAX_RANGES"] * RANGE_SIZE > c["REAL_STACK_TOP"] - 0x400:
        errs.append("boot_info overlaps the real-mode stack")
    if c["KERNEL_BATCH_SECTORS"] > 127:
        errs.append("KERNEL_BATCH_SECTORS must be <= 127 (BIOS EDD limit)")
    if c["KERNEL_BATCH_SECTORS"] * SECTOR > 0x10000:
        errs.append("a batch must fit in one 64 KiB segment")
    if c["IMAGE_SIZE_MIB"] * 1024 * 1024 // SECTOR <= c["EDUFS_START_LBA"] + 1024:
        errs.append("image too small for EduFS")
    if errs:
        sys.exit("layout.conf invalid:\n  - " + "\n  - ".join(errs))


def cmd_layout(conf, outdir):
    c = load(conf)
    validate(c)
    os.makedirs(outdir, exist_ok=True)
    hdr = "; GENERATED by scripts/gen_layout.py from config/layout.conf -- do not edit\n"
    with open(os.path.join(outdir, "boot_constants.inc"), "w") as f:
        f.write(hdr)
        for k, v in c.items():
            f.write(f"{k} equ 0x{v:X}\n")
        f.write(f"BOOT_INFO_RANGES_OFFSET equ {BOOT_INFO_HEADER}\n")
    with open(os.path.join(outdir, "layout.h"), "w") as f:
        f.write("/* GENERATED by scripts/gen_layout.py from config/layout.conf -- do not edit */\n")
        f.write("#ifndef EDUOS_LAYOUT_H\n#define EDUOS_LAYOUT_H\n")
        for k, v in c.items():
            f.write(f"#define {k} 0x{v:X}u\n")
        f.write("#endif\n")
    with open(os.path.join(outdir, "layout.mk"), "w") as f:
        f.write("# GENERATED by scripts/gen_layout.py -- do not edit\n")
        for k, v in c.items():
            f.write(f"{k} := {v}\n")


def cmd_metadata(conf, kernel_bin, outdir):
    c = load(conf)
    validate(c)
    size = os.path.getsize(kernel_bin)
    sectors = (size + SECTOR - 1) // SECTOR
    if sectors == 0:
        sys.exit("kernel.bin is empty")
    if sectors > c["KERNEL_MAX_SECTORS"]:
        sys.exit(f"kernel is {sectors} sectors; loader limit is {c['KERNEL_MAX_SECTORS']} "
                 f"(KERNEL_MAX_SECTORS in config/layout.conf)")
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "loader_metadata.inc"), "w") as f:
        f.write("; GENERATED by scripts/gen_layout.py -- do not edit\n")
        f.write(f"KERNEL_BYTES equ {size}\nKERNEL_SECTORS equ {sectors}\n")
    print(f"kernel: {size} bytes, {sectors} sectors (limit {c['KERNEL_MAX_SECTORS']})")


if __name__ == "__main__":
    a = sys.argv[1:]
    if len(a) == 3 and a[0] == "layout":
        cmd_layout(a[1], a[2])
    elif len(a) == 4 and a[0] == "metadata":
        cmd_metadata(a[1], a[2], a[3])
    else:
        sys.exit(__doc__)
